# Speicher-Fix (v128): Der Spielstand (8D:AF89, 0x331 Byte je Platz) sichert 7E:2250-2257 (Waffe +N untere Halbbytes,
# Lade-Merker, NG+-Zyklus) und 7E:20B0-20C9 (Formel-/Talisman-+N) NICHT – nach Speichern/Laden waren sie weg
# (bei OpenEmu-Schnellspeichern fiel das nicht auf). Hier: nach jedem Speichern beide Bereiche je Platz in freies SRAM
# 30:7700 + Platz*64 (Merkzeichen "W+" an +34), beim Laden (8D:B2A0, vor dem bisherigen Hook F0:0380) zurueckholen.
# Platz: $0B3B = Platz*2 (Speichern CD:D120, Laden CD:B2BF lesen beide daraus).
import sys; sys.path.insert(0, __file__.rsplit('/',1)[0]); from asm import assemble
pfad = sys.argv[1]
d = bytearray(open(pfad,'rb').read()); H = len(d) % 1024; r = memoryview(d)[H:]
def at(x): return x & 0x3FFFFF if (x>>16) >= 0xC0 else (((x>>16)&0x3F)<<16)|(x&0xFFFF)
CODE, BASIS = 0xF1B600, 0x7700
o = at(0x8DB2A0); assert r[o] == 0x22; ALT_LADEN = list(r[o+1:o+4])          # bisher JSL F0:0380 (soe_ngplus_ende)
# Y/X = Zieladresse aus Platz: A = $0B3B*32 + BASIS
def ziel(): return [0xAF,0x3B,0x0B,0x7E, 0x29,0x06,0x00, 0x0A,0x0A,0x0A,0x0A,0x0A, 0x18, 0x69,BASIS&0xFF,BASIS>>8]
code, lab = assemble(CODE, [
  # ---- Speichern: ersetzt JSL 8D:AF89 an CD:D141
  # v129: in der DarkSoulCave (SRAM 30:7002) wird nicht gespeichert
  'sp:', [0x08, 0xC2,0x20, 0xAF,0x02,0x70,0x30, 0x29,0xFF,0x00, 0x28], ('bra8',0xF0,'sp_ja'), [0x6B],
  'sp_ja:', [0x22,0x89,0xAF,0x8D, 0x08, 0xC2,0x30, 0x48, 0xDA, 0x5A, 0x8B],
  ziel(), [0xA8, 0x5A],                                        # Y = Ziel, merken
  [0xA2,0x50,0x22, 0xA9,0x07,0x00, 0x54,0x30,0x7E],            # 2250..2257 -> Ziel+0   (MVN $30,$7E)
  [0x7A, 0x98, 0x18, 0x69,0x08,0x00, 0xA8, 0x5A],
  [0xA2,0xB0,0x20, 0xA9,0x19,0x00, 0x54,0x30,0x7E],            # 20B0..20C9 -> Ziel+8
  [0x7A, 0xA9,0x57,0x2B, 0xBB],                                # X = Ziel+8 ; "W+" an Ziel+34
  [0x8A, 0x18, 0x69,0x1A,0x00, 0xAA, 0xA9,0x57,0x2B, 0x9F,0x00,0x00,0x30],
  ziel(), [0xAA, 0xE2,0x20, 0xAF,0xCA,0x20,0x7E, 0x9F,0x24,0x00,0x30, 0xC2,0x20],   # v146e: Vulgor-Siegzaehler 20CA -> Ziel+0x24
  [0xAB, 0x7A, 0xFA, 0x68, 0x28, 0x6B],
  # ---- Laden: ersetzt JSL F0:0380 an 8D:B2A0
  'la:', [0x08, 0xC2,0x30, 0x48, 0xDA, 0x5A, 0x8B, 0xA9,0x00,0x00, 0x8F,0x02,0x70,0x30],   # v129: geladener Stand ist nie in der Hoehle
  ziel(), [0xAA, 0xBF,0x22,0x00,0x30, 0xC9,0x57,0x2B], ('bra8',0xD0,'la_0'),   # Merkzeichen da? (v146e: sonst Siegzaehler 0)
  [0xA0,0x50,0x22, 0xA9,0x07,0x00, 0x54,0x7E,0x30],            # Ziel+0 -> 2250..2257 (MVN $7E,$30)
  [0xA0,0xB0,0x20, 0xA9,0x19,0x00, 0x54,0x7E,0x30],          # X steht nach MVN schon auf Ziel+8
  ziel(), [0xAA, 0xE2,0x20, 0xBF,0x24,0x00,0x30, 0x8F,0xCA,0x20,0x7E, 0xC2,0x20],   # v146e: Siegzaehler zurueck
  ('bra8',0x80,'la_weg'),
  'la_0:', [0xE2,0x20, 0xA9,0x00, 0x8F,0xCA,0x20,0x7E, 0xC2,0x20],
  'la_weg:', [0xAB, 0x7A, 0xFA, 0x68, 0x28, 0x22]+ALT_LADEN+[0x6B],
])
o = at(CODE); assert all(b == 0xFF for b in r[o:o+len(code)]), "Platz belegt"; r[o:o+len(code)] = code
def jsl(lbl): a = lab[lbl]; return bytes([0x22, a&0xFF, (a>>8)&0xFF, a>>16])
o = at(0x8DD141); assert bytes(r[o:o+4]) == bytes([0x22,0x89,0xAF,0x8D]), bytes(r[o:o+4]).hex(); r[o:o+4] = jsl('sp')
o = at(0x8DB2A0); r[o:o+4] = jsl('la')
h = 0xFFC0
for _ in range(2):
    s = sum(r) & 0xFFFF; r[h+0x1E:h+0x20] = s.to_bytes(2,'little'); r[h+0x1C:h+0x1E] = (s^0xFFFF).to_bytes(2,'little')
open(pfad,'wb').write(d); print("Speicher-Fix eingebaut")
