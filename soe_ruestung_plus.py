# Ruestung +1 % je weiterem Exemplar (v158, Max: "Ausruestung, die man hat und nochmal bekommt, +1 % auf den Wert, so koennen
# die nur doppelt so stark werden"). Die Anzahl im Inventar (7E:231D + Nr, gespeichert) zaehlt: Abwehr = Wert * (1 + (Anzahl-1)/100),
# hoechstens +100 %. Abwehr-Summe: Junge 8F:84AC/84B6/84C0 (0AC0/0AC2/0AC4), Hund 8F:8628 (0ABE): je CLC ; ADC $C40000,X
# (X = Ruestungs-Zeiger 0x4142 + 10*Nr) -> JSL rp + NOP. A = Summe rein/raus, X bleibt.
import sys; sys.path.insert(0, __file__.rsplit('/',1)[0]); from asm import assemble
pfad = sys.argv[1]
d = bytearray(open(pfad,'rb').read()); H = len(d) % 1024; r = memoryview(d)[H:]
def at(x): return x & 0x3FFFFF if (x>>16) >= 0xC0 else (((x>>16)&0x3F)<<16)|(x&0xFFFF)
def L(a): return [a&0xFF,(a>>8)&0xFF,a>>16]
CODE = 0xF90700
STELLEN = [0x8F84AC, 0x8F84B6, 0x8F84C0, 0x8F8628]
code, lab = assemble(CODE, [
  'rp:', [0x08, 0xC2,0x30, 0xDA, 0x5A, 0x48],                                   # 1,S = Summe bisher
  [0xBF,0x00,0x00,0xC4, 0xA8],                                                   # Y = Wert
  [0x8A, 0x38, 0xE9,0x42,0x41], ('bra8',0x90,'rp_0'),                           # Nr = (X - 4142) / 10
  [0x8F,0x04,0x42,0x00, 0xE2,0x20, 0xA9,10, 0x8F,0x06,0x42,0x00, 0xC2,0x20, 0xEA,0xEA,0xEA,0xEA,0xEA,0xEA,0xEA,0xEA],
  [0xAF,0x14,0x42,0x00, 0xC9,40,0x00], ('bra8',0xB0,'rp_0'), [0xAA],
  [0xBF,0x1D,0x23,0x7E, 0x29,0xFF,0x00], ('bra8',0xF0,'rp_0'), [0x3A], ('bra8',0xF0,'rp_0'),   # n = Anzahl - 1
  [0xC9,101,0x00], ('bra8',0x90,'rp_n'), [0xA9,100,0x00], 'rp_n:', [0xAA],        # X = n (1..100)
  [0x98, 0xC9,0x8F,0x02], ('bra8',0x90,'rp_k'), [0xA9,0x8F,0x02], 'rp_k:', [0xA8],   # Wert hoechstens 655 (Produkt < 65536)
  [0xA9,0x00,0x00], 'rp_m:', [0x5A, 0x18, 0x63,0x01, 0x7A, 0xCA], ('bra8',0xD0,'rp_m'),   # A = Wert * n
  [0x8F,0x04,0x42,0x00, 0xE2,0x20, 0xA9,100, 0x8F,0x06,0x42,0x00, 0xC2,0x20, 0xEA,0xEA,0xEA,0xEA,0xEA,0xEA,0xEA,0xEA],
  [0xA3,0x05, 0xAA, 0xBF,0x00,0x00,0xC4, 0x18, 0x6F,0x14,0x42,0x00], ('bra8',0x80,'rp_a'),   # Wert + Wert*n/100
  'rp_0:', [0xA3,0x05, 0xAA, 0xBF,0x00,0x00,0xC4],
  'rp_a:', [0x18, 0x63,0x01, 0x83,0x01],
  [0x68, 0x7A, 0xFA, 0x28, 0x18, 0x6B],
])
o = at(CODE); assert all(b == 0xFF for b in r[o:o+len(code)]), 'F9:0700 belegt'; r[o:o+len(code)] = code
for s in STELLEN:
    o = at(s); assert bytes(r[o:o+5]) == bytes([0x18, 0x7F,0x00,0x00,0xC4]), (hex(s), bytes(r[o:o+5]).hex())
    r[o:o+5] = bytes([0x22]+L(lab['rp'])+[0xEA])
h = 0xFFC0
for _ in range(2):
    c = sum(r) & 0xFFFF; r[h+0x1E:h+0x20] = c.to_bytes(2,'little'); r[h+0x1C:h+0x1E] = (c^0xFFFF).to_bytes(2,'little')
open(pfad,'wb').write(d); print("Ruestung +1 %% je Exemplar, %d Bytes" % len(code))
