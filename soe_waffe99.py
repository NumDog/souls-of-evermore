# Waffe +N bis 99 (Max v122: "+15-Sperre weg, bis 99 – wir koennen ja New Game+99 machen").
# Bisher: je Waffe ein Halbbyte in 7E:2250-2256 (0..15). Neu: zweites Halbbyte (Sechzehner) in freien, mitgespeicherten
# Flag-Bytes 7E:22CE-22D0 + 22D3-22D6 (in allen 94 Spielstaenden von Max nie belegt, auch nicht im Ende-Stand).
# Waffe i = ID/2 - 1 (0..12), Byte b = i/2, Halbbyte i&1 (wie bisher). Hi-Byte-Adresse: b<3 -> 22CE+b, sonst 22D0+b.
# Wert = lo + 16*hi, hoechstens 99.
#   WGET (F1:B000): A(16) = Waffen-ID -> A = Wert (0 bei keiner Waffe). X/Y bleiben.
#   WINC (F1:B080): A(16) = Waffen-ID -> Wert +1 (hoechstens 99). Alle Register bleiben.
#   WCLR (F1:B140): alle Sechzehner loeschen (Neues Spiel / Startwaffe). Alle Register bleiben.
import sys; sys.path.insert(0, __file__.rsplit('/',1)[0]); from asm import assemble
pfad = sys.argv[1]
d = bytearray(open(pfad,'rb').read()); H = len(d) % 1024; r = memoryview(d)[H:]
def at(x): return x & 0x3FFFFF if (x>>16) >= 0xC0 else (((x>>16)&0x3F)<<16)|(x&0xFFFF)
WGET, WINC, WCLR = 0xF1B000, 0xF1B080, 0xF1B140
MAXW = 99
# hi-Adresse: X = b (16 Bit) -> X = b (b<3) oder b+2
def hix(n): return [[0x8A, 0xC9,0x03,0x00], ('bra8',0x90,'hx%d'%n), [0x1A,0x1A], 'hx%d:'%n, [0xAA]]
g, _ = assemble(WGET, [[0x08, 0xC2,0x30, 0xDA, 0x5A],
    [0xC9,0x02,0x00], ('bra8',0x90,'null'), [0xC9,0x1B,0x00], ('bra8',0xB0,'null'),
    [0x4A, 0x3A, 0x48, 0x4A, 0xAA, 0x68, 0x29,0x01,0x00, 0xA8],           # X = Byte, Y = oberes Halbbyte?
    [0xBF,0x50,0x22,0x7E, 0xC0,0x00,0x00], ('bra8',0xF0,'lo_u'), [0x4A,0x4A,0x4A,0x4A], 'lo_u:', [0x29,0x0F,0x00, 0x48],
    *hix(1),
    [0xBF,0xCE,0x22,0x7E, 0xC0,0x00,0x00], ('bra8',0xF0,'hi_u'), [0x4A,0x4A,0x4A,0x4A], 'hi_u:', [0x29,0x0F,0x00],
    [0x0A,0x0A,0x0A,0x0A, 0x18, 0x63,0x01, 0x83,0x01, 0x68],
    [0xC9,MAXW,0x00], ('bra8',0x90,'raus'), [0xA9,MAXW,0x00], ('bra8',0x80,'raus'),
    'null:', [0xA9,0x00,0x00],
    'raus:', [0x7A, 0xFA, 0x28, 0xC9,0x00,0x00, 0x6B]])   # Flags passend zu A (Aufrufer: BEQ, alle 16 Bit)
assert len(g) <= 0x80
i_, _ = assemble(WINC, [[0x08, 0xC2,0x30, 0xDA, 0x5A, 0x48],
    [0x22]+[WGET&0xFF,(WGET>>8)&0xFF,WGET>>16], [0xC9,MAXW,0x00], ('bra8',0x90,'geht'), ('jmp','fertig'),
    'geht:', [0xA3,0x01, 0xC9,0x02,0x00], ('bra8',0x90,'fertig_j'), [0xC9,0x1B,0x00], ('bra8',0xB0,'fertig_j'),
    [0x4A, 0x3A, 0x48, 0x4A, 0xAA, 0x68, 0x29,0x01,0x00, 0xA8],
    [0xE2,0x20, 0xBF,0x50,0x22,0x7E, 0xC0,0x00,0x00], ('bra8',0xD0,'oben'),
    [0x29,0x0F, 0xC9,0x0F], ('bra8',0xF0,'lo_ueber'), [0xBF,0x50,0x22,0x7E, 0x1A, 0x9F,0x50,0x22,0x7E], ('jmp','fertig'),
    'lo_ueber:', [0xBF,0x50,0x22,0x7E, 0x29,0xF0, 0x9F,0x50,0x22,0x7E], ('bra8',0x80,'hi_inc'),
    'oben:', [0x29,0xF0, 0xC9,0xF0], ('bra8',0xF0,'hi_ueber'), [0xBF,0x50,0x22,0x7E, 0x18, 0x69,0x10, 0x9F,0x50,0x22,0x7E], ('jmp','fertig'),
    'hi_ueber:', [0xBF,0x50,0x22,0x7E, 0x29,0x0F, 0x9F,0x50,0x22,0x7E],
    'hi_inc:', [0xC2,0x20], *hix(2), [0xE2,0x20],
    [0xBF,0xCE,0x22,0x7E, 0xC0,0x00,0x00], ('bra8',0xD0,'h_oben'), [0x1A, 0x9F,0xCE,0x22,0x7E], ('bra8',0x80,'fertig_j'),
    'h_oben:', [0x18, 0x69,0x10, 0x9F,0xCE,0x22,0x7E],
    'fertig_j:',
    'fertig:', [0xC2,0x30, 0x68, 0x7A, 0xFA, 0x28, 0x6B]])
assert len(i_) <= 0xA0
c, _ = assemble(WCLR, [[0x08, 0xE2,0x20, 0x48, 0xA9,0x00,
    0x8F,0xCE,0x22,0x7E, 0x8F,0xCF,0x22,0x7E, 0x8F,0xD0,0x22,0x7E,
    0x8F,0xD3,0x22,0x7E, 0x8F,0xD4,0x22,0x7E, 0x8F,0xD5,0x22,0x7E, 0x8F,0xD6,0x22,0x7E, 0x68, 0x28, 0x6B]])
for adr, code in ((WGET,g),(WINC,i_),(WCLR,c)):
    o = at(adr); assert all(b == 0xFF for b in r[o:o+len(code)]), hex(adr); r[o:o+len(code)] = code
h = 0xFFC0
for _ in range(2):
    s = sum(r) & 0xFFFF; r[h+0x1E:h+0x20] = s.to_bytes(2,'little'); r[h+0x1C:h+0x1E] = (s^0xFFFF).to_bytes(2,'little')
open(pfad,'wb').write(d); print("Waffe bis +99 eingebaut")
