# Vulgor-Kampf: Erscheint "Vulgors Herzkammer" (Vorlage $8E:D894), erscheint zusaetzlich ein Raptor (Nr 110, $8E:D644).
# Hook: 8F:B045 (Gegner erscheinen lassen) -> JML auf eigene Kopie der Routine + Zusatz.
import sys; sys.path.insert(0, __file__.rsplit('/',1)[0]); from asm import assemble
pfad = sys.argv[1]
d = bytearray(open(pfad,'rb').read()); H = len(d) % 1024; r = memoryview(d)[H:]
def at(x): return x & 0x3FFFFF if (x>>16) >= 0xC0 else (((x>>16)&0x3F)<<16)|(x&0xFFFF)
SPAWN = 0xF01800
HERZ, RAPTOR = 0xD894, 0xD644
code,_ = assemble(SPAWN, [
  [0x8B, 0xF4,0x7E,0x7E, 0xAB,0xAB, 0x22,0x6F,0xB2,0x8F, 0x22,0x55,0xB0,0x8F, 0xAB],   # Original 8F:B045..B053
  [0x08, 0xC2,0x30, 0x48,0xDA,0x5A],                                                   # PHP REP#$30 PHA PHX PHY
  [0xA5,0x02, 0xC9,HERZ&0xFF,HERZ>>8], ('bra8',0xD0,'fertig'),
  [0xA5,0x02,0x48, 0xA5,0x46,0x48, 0xA5,0x48,0x48, 0xA5,0x08,0x48, 0xA5,0x4C,0x48],   # $02 $46 $48 $08 $4C sichern
  [0xA9,RAPTOR&0xFF,RAPTOR>>8, 0x85,0x02],                                             # Vorlage Raptor
  [0xA5,0x48, 0x18,0x69,0x30,0x00, 0x85,0x48],                                         # 48 Pixel unter dem Boss
  [0x64,0x08],
  [0x22,0x45,0xB0,0x8F],                                                               # JSL 8F:B045 (spawnt Raptor)
  [0x68,0x85,0x4C, 0x68,0x85,0x08, 0x68,0x85,0x48, 0x68,0x85,0x46, 0x68,0x85,0x02],   # zurueckholen
  'fertig:', [0x7A,0xFA,0x68,0x28, 0x6B],
])
o=at(SPAWN); assert all(b==0xFF for b in r[o:o+len(code)]); r[o:o+len(code)]=code
o=at(0x8FB045); assert bytes(r[o:o+4])==bytes([0x8B,0xF4,0x7E,0x7E]); r[o:o+4]=bytes([0x5C,SPAWN&0xFF,(SPAWN>>8)&0xFF,SPAWN>>16])
h=0xFFC0
for _ in range(2):
    c=sum(r)&0xFFFF; r[h+0x1E:h+0x20]=c.to_bytes(2,'little'); r[h+0x1C:h+0x1E]=(c^0xFFFF).to_bytes(2,'little')
open(pfad,'wb').write(d); print("Vulgor-Raptor eingebaut, %d Bytes"%len(code))
