# Level-Verlust beim Tod (Max 18.11., v116): Junge stirbt -> Level -1 (nicht unter 1), Werte neu (8F:8388), Erfahrung auf den
# Anfang des neuen Levels (Tabelle F1:6000, soe_grenzen) + Schwelle neu (F1:8000). Das Level liegt wie das Geld am Todesort
# (Merker SRAM 30:7E70). Abholen (soe_aufstehen 'f_holen') -> Level +1 zurueck. Erneuter Tod vorher -> Merker neu (altes Level weg).
import sys; sys.path.insert(0, __file__.rsplit('/',1)[0]); from asm import assemble
pfad = sys.argv[1]
d = bytearray(open(pfad,'rb').read()); H = len(d) % 1024; r = memoryview(d)[H:]
def at(x): return x & 0x3FFFFF if (x>>16) >= 0xC0 else (((x>>16)&0x3F)<<16)|(x&0xFFFF)
def L(a): return [a&0xFF,(a>>8)&0xFF,a>>16]
LVTOD, LVHOL = 0xF18C00, 0xF18C80
MERK = 0x307E70
EXPJ, SCHW = 0xF16000, 0xF18000
def neu():   # Level in A gesetzt (16 bit): Werte + Erfahrung + Schwelle
    return [0x8F,0x50,0x0A,0x7E, 0x85,0x02, 0x64,0x04, 0x22,0x88,0x83,0x8F,                  # STA 0A50 ; $02 = Level ; STZ $04 ; Werte neu
            0xAF,0x50,0x0A,0x7E, 0x0A,0x0A, 0xAA, 0xBF]+L(EXPJ)+[0x8F,0x49,0x0A,0x7E, 0xBF]+L(EXPJ+2)+[0x8F,0x4B,0x0A,0x7E,
            0x22]+L(SCHW)
t = ['tod:', [0x08, 0xC2,0x30, 0xDA, 0x5A, 0xA5,0x02, 0x48, 0xA5,0x04, 0x48,
              0xA9,0x00,0x00, 0x8F]+L(MERK)+[0xAF,0x50,0x0A,0x7E, 0xC9,0x02,0x00], ('bra8',0x90,'t_raus'),
     [0x3A], neu(), [0xA9,0x01,0x00, 0x8F]+L(MERK),
     't_raus:', [0x68, 0x85,0x04, 0x68, 0x85,0x02, 0x7A, 0xFA, 0x28, 0x6B]]
c1,_ = assemble(LVTOD, t)
h = ['hol:', [0x08, 0xC2,0x30, 0xDA, 0x5A, 0xA5,0x02, 0x48, 0xA5,0x04, 0x48,
              0xAF]+L(MERK), ('bra8',0xF0,'h_raus'), [0xA9,0x00,0x00, 0x8F]+L(MERK),
     [0xAF,0x50,0x0A,0x7E, 0xC9,0xE7,0x03], ('bra8',0xB0,'h_raus'), [0x1A], neu(),
     'h_raus:', [0x68, 0x85,0x04, 0x68, 0x85,0x02, 0x7A, 0xFA, 0x28, 0x6B]]
c2,_ = assemble(LVHOL, h)
for a,c in ((LVTOD,c1),(LVHOL,c2)):
    o = at(a); assert all(b == 0xFF for b in r[o:o+len(c)]) and len(c) <= 0x80, (hex(a), len(c)); r[o:o+len(c)] = c
hh = 0xFFC0
for _ in range(2):
    s = sum(r) & 0xFFFF; r[hh+0x1E:hh+0x20] = s.to_bytes(2,'little'); r[hh+0x1C:hh+0x1E] = (s^0xFFFF).to_bytes(2,'little')
open(pfad,'wb').write(d); print("Level-Verlust beim Tod eingebaut")
