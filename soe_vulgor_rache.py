# Vulgors Rache: Bekommt man im Vulgor-Raum (Karte 0x18) eine neue Waffe (Belohnung, z. B. Tarantelaxt; Besitz 22DA/22DB),
# erscheinen ~3 s spaeter bis zu 10 Raptoren (so viele, wie Objekt-Plaetze frei sind, minus 2) (Gegner 89 Dschungel-Raptor, Skript-Index 0x2B; im Vulgor-Raum HP/Angriff x3, siehe STAERKE)
# an festen Stellen der Arena (Kachel 20/46 und 26/46, Eingang ist 23/53). ($46/$48 beim Larven-Erscheinen ist keine Position.)
# Erzeugt ueber den echten Skriptbefehl BA <idx> <x> <y> in einem Mini-Skript (SRAM $30:7FD8), Faden wie in soe_aufstehen.py.
# Pruefung jedes Bild in der Hauptschleife (Hook 8E:E431 JSL $91C62E). Merker: 7FD2 = Zaehler, 7FD4 = erledigt, 7FE2 = A5 (Besitz gemerkt), 7FE4 = gemerkter Besitz.
import sys; sys.path.insert(0, __file__.rsplit('/',1)[0]); from asm import assemble
pfad = sys.argv[1]
d = bytearray(open(pfad,'rb').read()); H = len(d) % 1024; r = memoryview(d)[H:]
def at(x): return x & 0x3FFFFF if (x>>16) >= 0xC0 else (((x>>16)&0x3F)<<16)|(x&0xFFFF)
CODE = 0xF04000
ANZ = 10                                   # Raptoren (Max: 10)
POS = 0xF04180                             # Kachel-Positionen x,y je Raptor
POSTAB = bytes(sum(([18+2*(k%5), 44 if k < 5 else 48] for k in range(ANZ)), []))
code, lab = assemble(CODE, [
  'start:', [0x22,0x2E,0xC6,0x91, 0x08, 0xC2,0x30, 0xDA, 0x5A],                       # Original + sichern
  [0xAF,0xDB,0x0A,0x7E, 0x29,0xFF,0x00, 0xC9,0x18,0x00], ('bra8',0xF0,'vulgor'),
  [0xA9,0x00,0x00, 0x8F,0xD2,0x7F,0x30, 0x8F,0xD4,0x7F,0x30, 0x8F,0xE2,0x7F,0x30], ('jmp','raus'),   # anderer Raum: alles zuruecksetzen
  'vulgor:', [0xAF,0xD4,0x7F,0x30, 0x29,0xFF,0x00], ('bra8',0xF0,'v_offen'), ('jmp','raus'),        # schon erledigt
  'v_offen:', [0xAF,0xD2,0x7F,0x30, 0x29,0xFF,0x00], ('bra8',0xF0,'beobachten'),
  [0x3A, 0x8F,0xD2,0x7F,0x30], ('bra8',0xF0,'rache'), ('jmp','raus'),                             # Zaehler laeuft
  # Waffen-Besitz beobachten: neue Waffe im Vulgor-Raum (Belohnung) -> Zaehler 180 (~3 s)
  'beobachten:', [0xAF,0xE2,0x7F,0x30, 0x29,0xFF,0x00, 0xC9,0xA5,0x00], ('bra8',0xF0,'vergleich'),
  [0xA9,0xA5,0x00, 0x8F,0xE2,0x7F,0x30, 0xAF,0xDA,0x22,0x7E, 0x8F,0xE4,0x7F,0x30], ('jmp','raus'),   # erster Blick: merken
  'vergleich:', [0xAF,0xDA,0x22,0x7E, 0x4F,0xE4,0x7F,0x30, 0x2F,0xDA,0x22,0x7E], ('bra8',0xD0,'neu'),  # neue Bits?
  ('jmp','raus'),
  'neu:', [0xAF,0xDA,0x22,0x7E, 0x8F,0xE4,0x7F,0x30, 0xA9,0xB4,0x00, 0x8F,0xD2,0x7F,0x30], ('jmp','raus'),
  'rache:', [0xA9,0x01,0x00, 0x8F,0xD4,0x7F,0x30],                                     # nur einmal
  # freie Objekt-Plaetze zaehlen (Freiliste ab $3DE3, weiter ueber +$5E) -> sonst BRK in 8F:B28E
  [0xA0,0x00,0x00, 0xAF,0xE3,0x3D,0x7E],
  'z_frei:', ('bra8',0xF0,'z_fertig'), [0xC8, 0xAA, 0xBF,0x5E,0x00,0x7E], ('bra8',0x80,'z_frei'),
  'z_fertig:', [0x98, 0x38, 0xE9,0x02,0x00], ('bra8',0xB0,'n_pos'), ('jmp','raus'),             # Anzahl = frei - 2
  'n_pos:', ('bra8',0xD0,'n_nz'), ('jmp','raus'),
  'n_nz:', [0xC9,ANZ,0x00], ('bra8',0x90,'n_ok'), [0xA9,ANZ,0x00], 'n_ok:', [0x8F,0xD6,0x7F,0x30],  # hoechstens ANZ
  # Mini-Skript in SRAM $30:7F90: n x (BA 0D x y), dann 00
  [0xA2,0x00,0x00, 0xA0,0x00,0x00],
  'm_loop:', [0xE2,0x20, 0xA9,0xBA, 0x9F,0x90,0x7F,0x30, 0xA9,0x2B, 0x9F,0x91,0x7F,0x30, 0xC2,0x20],
  [0xDA, 0x98, 0x0A, 0xAA, 0xBF,POS&0xFF,(POS>>8)&0xFF,POS>>16, 0xFA, 0x9F,0x92,0x7F,0x30],   # x | y<<8 -> 7F92/7F93
  [0xE8,0xE8,0xE8,0xE8, 0xC8, 0x98, 0xCF,0xD6,0x7F,0x30], ('bra8',0x90,'m_loop'),
  [0xE2,0x20, 0xA9,0x00, 0x9F,0x90,0x7F,0x30, 0xC2,0x20],
  [0x64,0x26, 0x64,0x28, 0x22,0xFD,0xD2,0x8C],
  [0xA9,0x90,0x7F, 0x9F,0x00,0x00,0x7E, 0xE2,0x20, 0xA9,0x30, 0x9F,0x02,0x00,0x7E, 0xC2,0x20],
  [0xA9,0x00,0x00, 0x9F,0x0B,0x00,0x7E, 0x9F,0x0D,0x00,0x7E],
  [0x8A, 0xA6,0x86, 0x9F,0x28,0x2F,0x7E, 0xE8,0xE8, 0xA9,0x00,0x00, 0x9F,0x28,0x2F,0x7E, 0x86,0x86],
  'raus:', [0x7A, 0xFA, 0x28, 0x6B],
])
o = at(CODE); assert all(b == 0xFF for b in r[o:o+len(code)]) and CODE + len(code) <= POS, hex(CODE+len(code)); r[o:o+len(code)] = code
o = at(POS); assert all(b == 0xFF for b in r[o:o+len(POSTAB)]); r[o:o+len(POSTAB)] = POSTAB
o = at(0x8EE431); assert bytes(r[o:o+4]) == bytes([0x22,0x2E,0xC6,0x91]); r[o:o+4] = bytes([0x22, CODE&0xFF, (CODE>>8)&0xFF, CODE>>16])
h = 0xFFC0
for _ in range(2):
    c = sum(r) & 0xFFFF; r[h+0x1E:h+0x20] = c.to_bytes(2,'little'); r[h+0x1C:h+0x1E] = (c^0xFFFF).to_bytes(2,'little')
open(pfad,'wb').write(d); print("Vulgors Rache eingebaut, %d Bytes" % len(code))
