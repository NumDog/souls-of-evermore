# NG+-Datensatz: STASH (WRAM -> SRAM $30:7C04.., Merkzeichen "NG" bei $30:7C00) und RESTORE bei "Neues Spiel" (Hook 8F:8093).
import sys; sys.path.insert(0, __file__.rsplit('/',1)[0]); from asm import assemble
BLOECKE = [(0x2210,0x2250),(0x0A35,0x0A52),(0x0A7F,0x0A9C),(0x0AC6,0x0AD2),(0x0ADD,0x0AF9),(0x0B07,0x0B08),
           (0x2250,0x225D),(0x2262,0x2263),(0x22DA,0x22DC),(0x22FF,0x2348),(0x2F52,0x2FDE),(0x4F1D,0x4F21),(0x20B0,0x20C9),(0x22CE,0x22D1),(0x22D3,0x22D7)]   # v122: Waffe-Sechzehner (soe_waffe99)   # + Formel-Zaehler +N (v88) + Talisman-Zaehler (v92)
SRAM0 = 0x7C04          # Datenbeginn in Bank $30
def layout():
    out=[]; s=SRAM0
    for a,e in BLOECKE: out.append((a,e-a,s)); s+=e-a
    assert s <= 0x8000; return out
STASH, RESTORE = 0xF00400, 0xF00500
TRIGGER, NAMEFIX = 0xF00700, 0xF00780
def build(r):
    def at(x): return x & 0x3FFFFF if (x>>16) >= 0xC0 else (((x>>16)&0x3F)<<16)|(x&0xFFFF)
    L = layout()
    # ---------- STASH: WRAM -> SRAM, Merkzeichen "NG"
    st = [[0x08,0xC2,0x30,0x8B]]
    for w,n,s in L: st.append([0xA2,w&0xFF,w>>8, 0xA0,s&0xFF,s>>8, 0xA9,(n-1)&0xFF,(n-1)>>8, 0x54,0x30,0x7E])
    st += [[0xE2,0x20, 0xAF,0x61,0x22,0x7E, 0x8F,0x03,0x7C,0x30,   # v92: 2261 (Talismane Bit5-7) -> 30:7C03
             0xAF,0x63,0x22,0x7E, 0x8F,0x02,0x7C,0x30, 0xA9,0x4E, 0x8F,0x00,0x7C,0x30, 0xA9,0x47, 0x8F,0x01,0x7C,0x30, 0xAB,0x28,0x6B]]
    s_code,_ = assemble(STASH, st)
    def mask(addr, andv): return [0xAF,addr&0xFF,addr>>8,0x7E, 0x29,andv, 0x8F,addr&0xFF,addr>>8,0x7E]
    # ---------- RESTORE (an 8D:B2A0, nach Grundeinstellung/Laden): nur bei Merkzeichen UND frischem Spiel
    items = [[0x08,0xC2,0x30,0x8B,0xDA,0x5A,0x48],                      # PHP REP#$30 PHB PHX PHY PHA
             [0xAF,0x00,0x7C,0x30, 0xC9,0x4E,0x47], ('bra8',0xD0,'raus_n'),  # Merkzeichen "NG"?
             [0xAF,0x50,0x0A,0x7E, 0xC9,0x01,0x00], ('bra8',0xD0,'raus_n'),  # Level 1?
             [0xAF,0xDA,0x22,0x7E, 0x29,0xE9,0xFF], ('bra8',0xD0,'raus_n'),  # nur Startwaffen: Knochenknueppel (02), Drachentoeter (04), Laserschwert (10)?
             [0xAF,0x58,0x22,0x7E, 0x0F,0x5A,0x22,0x7E], ('bra8',0xF0,'los'),  # keine Formeln?
             'raus_n:', ('jmp','raus'),
             'los:']
    for w,n,s in L: items.append([0xA2,s&0xFF,s>>8, 0xA0,w&0xFF,w>>8, 0xA9,(n-1)&0xFF,(n-1)>>8, 0x54,0x7E,0x30])
    items += [[0xE2,0x20],
             [0xAF,0x57,0x22,0x7E, 0x1A, 0xC9,100], ('bra8',0x90,'z_ok'), [0xA9,99], 'z_ok:', [0x8F,0x57,0x22,0x7E],   # v97: max NG+99
             [0xAF,0x56,0x22,0x7E, 0x09,0x80, 0x8F,0x56,0x22,0x7E],
             [0xA9,0x00,0x8F,0x04,0x23,0x7E],                       # Matschpfeffer ($2304) = 0 (Story)
             mask(0x22DA,0xBF), mask(0x22DB,0x3B), mask(0x225A,0xDF), mask(0x225B,0xEF), mask(0x225C,0x7F), mask(0x2263,0xF8),
             [0xAF,0x02,0x7C,0x30, 0x29,0x07, 0x0F,0x63,0x22,0x7E, 0x8F,0x63,0x22,0x7E],
             mask(0x2261,0x1F), [0xAF,0x03,0x7C,0x30, 0x29,0xE0, 0x0F,0x61,0x22,0x7E, 0x8F,0x61,0x22,0x7E],   # v92: Armor Ultra/Chocobo/Insektengift behalten
             [0xA9,0x00, 0x8F,0x00,0x7C,0x30, 0x8F,0x01,0x7C,0x30],
             [0xC2,0x20, 0xAF,0x35,0x0A,0x7E, 0x8F,0xB3,0x4E,0x7E, 0xAF,0x7F,0x0A,0x7E, 0x8F,0x61,0x4F,0x7E, 0xE2,0x20],  # HP auffuellen
             [0x22,NAMEFIX&0xFF,(NAMEFIX>>8)&0xFF,NAMEFIX>>16],
             'raus:', [0xC2,0x30,0x68,0x7A,0xFA,0xAB,0x28,0x6B]]
    r_code,_ = assemble(RESTORE, items)
    # ---------- NAMEFIX: Name "Max" / "Max+3" -> "Max+<Zyklus>" (8 bit A, 16 bit X)
    nf = [[0x08,0xE2,0x20,0xC2,0x10],                     # PHP SEP#$20 REP#$10
          [0xA2,0x00,0x00],                               # LDX #0
          'such:', [0xBF,0x10,0x22,0x7E], ('bra8',0xF0,'ende_name'),   # LDA $7E2210,X ; BEQ
          [0xC9,0x2B], ('bra8',0xF0,'ende_name'),         # '+' -> hier abschneiden
          [0xE8,0xE0,0x0C,0x00], ('bra8',0x90,'such'),    # INX ; CPX #12 ; BCC
          'ende_name:',
          [0xA9,0x2B,0x9F,0x10,0x22,0x7E,0xE8],           # '+' schreiben
          [0xAF,0x57,0x22,0x7E],                          # Zyklus
          [0xC9,0x0A], ('bra8',0x90,'einer'),             # < 10?
          [0xA0,0x00,0x00], 'zehn:', [0xC9,0x0A], ('bra8',0x90,'zehn_fertig'), [0xE9,0x0A,0xC8], ('bra8',0x80,'zehn'),
          'zehn_fertig:', [0x48,0x98,0x18,0x69,0x30,0x9F,0x10,0x22,0x7E,0xE8,0x68],   # Zehner-Ziffer
          'einer:', [0x18,0x69,0x30,0x9F,0x10,0x22,0x7E,0xE8],                         # Einer-Ziffer
          [0xA9,0x00,0x9F,0x10,0x22,0x7E],                # Ende-Null
          [0x28,0x6B]]
    n_code,_ = assemble(NAMEFIX, nf)
    # ---------- TRIGGER an 8C:DF82 (Skript laedt Karte): bei Karte 0x63 + beide Helden weg + echter Name -> STASH
    tg = [[0x8D,0xDB,0x0A],                               # STA $0ADB (Original)
          [0x08,0xC2,0x30,0x48,0xDA,0x5A],                # PHP REP#$30 PHA PHX PHY
          [0x22,RESTORE&0xFF,(RESTORE>>8)&0xFF,RESTORE>>16],   # frisches Spiel + Merkzeichen? -> NG+ zurueckholen
          [0xA3,0x05],                                    # LDA 5,S (gesicherter A-Wert = Kartennummer)
          [0xC9,0x63,0x00], ('bra8',0xD0,'weiter'),
          [0xAF,0x61,0x22,0x7E, 0x29,0x03,0x00, 0xC9,0x03,0x00], ('bra8',0xD0,'weiter'),
          [0xAF,0x10,0x22,0x7E, 0x29,0xFF,0x00], ('bra8',0xF0,'weiter'),
          [0x22,STASH&0xFF,(STASH>>8)&0xFF,STASH>>16],
          'weiter:', [0x7A,0xFA,0x68,0x28],               # PLY PLX PLA PLP
          [0x22,0x95,0x8E,0x90],                          # JSL $908E95 (Original)
          [0x6B]]
    t_code,_ = assemble(TRIGGER, tg)
    def sram_of(wa):
        for w_,n_,s_ in L:
            if w_ <= wa < w_+n_: return s_ + (wa-w_)
        raise KeyError(hex(wa))
    NAME_S, DOG_S, ZYK_S = sram_of(0x2210), sram_of(0x2234), sram_of(0x2257)
    NAMESKIP, DOGSKIP, LABEL = 0xF00800, 0xF00880, 0xF00900
    ns,_ = assemble(NAMESKIP, [[0xAF,0x00,0x7C,0x30, 0xC9,0x4E,0x47], ('bra8',0xF0,'ng'), [0x5C,0x4F,0x82,0x8D],
        'ng:', [0x8B, 0xA2,NAME_S&0xFF,NAME_S>>8, 0xA0,0x10,0x22, 0xA9,35,0, 0x54,0x7E,0x30, 0xAB],
        [0x22,0x72,0xB1,0x80, 0x18, 0x6B]])
    ds,_ = assemble(DOGSKIP, [
        [0xAF,0x00,0x7C,0x30, 0xC9,0x4E,0x47], ('bra8',0xF0,'ngp'),           # Datensatz bereit?
        [0xAF,0x57,0x22,0x7E, 0x29,0xFF,0x00], ('bra8',0xF0,'normal'),        # oder schon NG+ (Zyklus>=1)?
        'ngp:',
        [0xA5,0x22, 0xC9,0x10,0x22], ('bra8',0xD0,'hund'),
        [0x8B, 0xA2,NAME_S&0xFF,NAME_S>>8, 0xA0,0x10,0x22, 0xA9,35,0, 0x54,0x7E,0x30, 0xAB], ('bra8',0x80,'fertig'),
        'hund:', [0xC9,0x34,0x22], ('bra8',0xD0,'normal'),
        [0x8B, 0xA2,DOG_S&0xFF,DOG_S>>8, 0xA0,0x34,0x22, 0xA9,27,0, 0x54,0x7E,0x30, 0xAB],
        'fertig:', [0xAF,0x10,0x22,0x7E, 0x29,0xFF,0x00], ('bra8',0xF0,'normal'),   # leerer Name im Datensatz -> doch eingeben
        [0x22,0x72,0xB1,0x80, 0x18, 0x6B],
        'normal:', [0x5C,0x4F,0x82,0x8D]])
    TXT = 0xF00A00; txt = b"New Game +"
    lb,_ = assemble(LABEL, [[0xAF,0x00,0x7C,0x30, 0xC9,0x4E,0x47], ('bra8',0xF0,'ng'),
        [0xA9,0x33,0x23,0x85,0x22, 0xA9,0xC5,0x00,0x85,0x24, 0x6B],
        'ng:', [0xDA,0x5A,0x8B, 0xA2,TXT&0xFF,(TXT>>8)&0xFF, 0xA0,0x00,0x7E, 0xA9,len(txt)-1,0, 0x54,0x30,0xF0, 0xAB],   # PHX PHY; "New Game +" -> $30:7E00
        [0x08,0xE2,0x20, 0xA2,len(txt),0x00],                       # PHP SEP#$20 LDX #10
        [0xAF,ZYK_S&0xFF,ZYK_S>>8,0x30, 0x1A, 0xC9,100], ('bra8',0x90,'z_ok'), [0xA9,99], 'z_ok:',   # Zyklus+1 (max 99, v97)
        [0xC9,100], ('bra8',0x90,'unter100'),
        [0xA0,0,0], 'h:', [0xC9,100], ('bra8',0x90,'h_ok'), [0xE9,100,0xC8], ('bra8',0x80,'h'),
        'h_ok:', [0x48,0x98,0x18,0x69,0x30,0x9F,0x00,0x7E,0x30,0xE8,0x68], ('bra8',0x80,'zehner_immer'),
        'unter100:', [0xC9,10], ('bra8',0x90,'einer'),
        'zehner_immer:', [0xA0,0,0], 'z:', [0xC9,10], ('bra8',0x90,'z_fertig'), [0xE9,10,0xC8], ('bra8',0x80,'z'),
        'z_fertig:', [0x48,0x98,0x18,0x69,0x30,0x9F,0x00,0x7E,0x30,0xE8,0x68],
        'einer:', [0x18,0x69,0x30,0x9F,0x00,0x7E,0x30,0xE8, 0xA9,0x00,0x9F,0x00,0x7E,0x30],
        [0x28, 0xA9,0x00,0x7E,0x85,0x22, 0xA9,0x30,0x00,0x85,0x24, 0x7A,0xFA, 0x6B]])   # PLP ... PLY PLX
    MENUNAME = 0xF00870
    mn = bytes([0xA9,0x7E,0x00,0x85,0x24, 0x4C,DOGSKIP&0xFF,(DOGSKIP>>8)&0xFF])     # LDA #$7E STA $24 ; JMP DOGSKIP
    o=at(0x8DCBD5); assert bytes(r[o:o+13])==bytes([0xA9,0x10,0x22,0x85,0x22,0xA9,0x7E,0x00,0x85,0x24,0x4C,0x4F,0x82]), bytes(r[o:o+13]).hex()
    r[o:o+13]=bytes([0xA9,0x10,0x22,0x85,0x22, 0x5C,MENUNAME&0xFF,(MENUNAME>>8)&0xFF,MENUNAME>>16, 0xEA,0xEA,0xEA,0xEA])
    for adr,code in ((NAMESKIP,ns),(DOGSKIP,ds),(LABEL,lb),(TXT,txt),(MENUNAME,mn)):
        o=at(adr); assert all(b==0xFF for b in r[o:o+len(code)]), hex(adr); r[o:o+len(code)]=code
    for site,orig,new in ((0x808C24,bytes([0x22,0x4F,0x82,0x8D]),bytes([0x22,NAMESKIP&0xFF,(NAMESKIP>>8)&0xFF,NAMESKIP>>16])),
                          (0x8CE5CB,bytes([0x22,0x4F,0x82,0x8D]),bytes([0x22,DOGSKIP&0xFF,(DOGSKIP>>8)&0xFF,DOGSKIP>>16])),
                          (0x8DC924,bytes([0xA9,0x33,0x23,0x85,0x22,0xA9,0xC5,0x00,0x85,0x24]),bytes([0x22,LABEL&0xFF,(LABEL>>8)&0xFF,LABEL>>16,0xEA,0xEA,0xEA,0xEA,0xEA,0xEA]))):
        o=at(site); assert bytes(r[o:o+len(orig)])==orig, hex(site); r[o:o+len(orig)]=new
    for adr,code in ((STASH,s_code),(RESTORE,r_code),(NAMEFIX,n_code),(TRIGGER,t_code)):
        o=at(adr); assert all(b==0xFF for b in r[o:o+len(code)]), hex(adr); r[o:o+len(code)]=code
    o=at(0x8CDF82); assert bytes(r[o:o+7])==bytes([0x8D,0xDB,0x0A,0x22,0x95,0x8E,0x90]), bytes(r[o:o+7]).hex()
    r[o:o+7]=bytes([0x22,TRIGGER&0xFF,(TRIGGER>>8)&0xFF,TRIGGER>>16,0xEA,0xEA,0xEA])
    # RESTORE vor den Lade-Hook (F00300) haengen: F00300 beginnt mit LDA $0ABA -> davor JSL RESTORE
    o=at(0xF00300); assert bytes(r[o:o+3])==bytes([0xAD,0xBA,0x0A])
    o2=at(0xF00380); assert all(b==0xFF for b in r[o2:o2+16])
    r[o2:o2+4]=bytes([0x22,RESTORE&0xFF,(RESTORE>>8)&0xFF,RESTORE>>16]); r[o2+4:o2+8]=bytes([0x5C,0x00,0x03,0xF0])   # JSL RESTORE ; JML F00300
    o=at(0x8DB2A0); assert bytes(r[o:o+4])==bytes([0x22,0x00,0x03,0xF0]); r[o:o+4]=bytes([0x22,0x80,0x03,0xF0])
    return len(s_code), len(r_code), len(n_code), len(t_code)
