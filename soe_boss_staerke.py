# Bossraum-Gegner staerker (v146z2, Max: "Endboss-Raptoren gehen mit einem Schlag weg, Lavarex nur 400 KP").
# Jedes Bild (Kette F0:4000): in der Cave (AKT 30:7002) im Bossraum (BOSSAKT 30:703A), nicht Vulgor-Raum 0x18:
# jedes neu erschienene Monster (Vorlage C536..DF3A) mit 1..999 KP bekommt KP x 10.
# Merkliste je Objekt-Slot 7E:EEC0 + 2k: gemerkte Vorlage; tot (KP 0) -> 0, damit Wellen im selben Slot wieder zaehlen.
# Ausserhalb des Bossraums wird nur gemerkt (MODUS 7E:EEFC = 0).
import sys; sys.path.insert(0, __file__.rsplit('/',1)[0]); from asm import assemble
pfad = sys.argv[1]
d = bytearray(open(pfad,'rb').read()); H = len(d) % 1024; r = memoryview(d)[H:]
def at(x): return x & 0x3FFFFF if (x>>16) >= 0xC0 else (((x>>16)&0x3F)<<16)|(x&0xFFFF)
def L(a): return [a&0xFF, (a>>8)&0xFF, a>>16]
CODE = 0xF8F800
o0 = at(0xF04000); assert r[o0] == 0x22; vorbild = list(r[o0+1:o0+4])
code, lab = assemble(CODE, [
  'bs:', [0x22]+vorbild+[0x08, 0xC2,0x30, 0x48, 0xDA, 0x5A, 0x8B, 0xF4,0x7E,0x7E, 0xAB,0xAB],
  [0xAF,0x02,0x70,0x30, 0x29,0xFF,0x00], ('bra8',0xD0,'bs_akt'), ('jmp','bs_aus'),
  'bs_akt:', [0x9C,0xFC,0xEE],                                        # MODUS = 0
  [0xAF,0x3A,0x70,0x30], ('bra8',0xF0,'bs_go'),
  [0xAD,0xDB,0x0A, 0x29,0xFF,0x00, 0xC9,0x18,0x00], ('bra8',0xF0,'bs_go'),
  [0xA9,0x01,0x00, 0x8D,0xFC,0xEE],                                  # MODUS = 1 (Bossraum)
  'bs_go:', [0xA2,0xE5,0x3D, 0xA0,0x00,0x00],
  'bs_l:', [0xBD,0x2A,0x00], ('bra8',0xD0,'bs_lebt'), [0xA9,0x00,0x00, 0x99,0xC0,0xEE], ('bra8',0x80,'bs_n'),
  'bs_lebt:', [0xBD,0x60,0x00, 0xD9,0xC0,0xEE], ('bra8',0xF0,'bs_n'), [0x99,0xC0,0xEE],
  [0xAD,0xFC,0xEE], ('bra8',0xF0,'bs_n'),
  [0xBD,0x60,0x00, 0xC9,0x36,0xC5], ('bra8',0x90,'bs_n'), [0xC9,0x3B,0xDF], ('bra8',0xB0,'bs_n'),
  [0xBD,0x2A,0x00, 0xC9,0xE8,0x03], ('bra8',0xB0,'bs_n'),            # nur 1..999 KP
  [0x0A, 0x8D,0xFE,0xEE, 0x0A, 0x0A, 0x18, 0x6D,0xFE,0xEE, 0xC9,0xD0,0x07, 0xB0,0x03, 0xA9,0xD0,0x07, 0x9D,0x2A,0x00],   # KP x 10, mindestens 2000
  'bs_n:', [0xC8, 0xC8, 0x8A, 0x18, 0x69,0x8E,0x00, 0xAA, 0xE0,0x89,0x4E], ('bra8',0x90,'bs_l'),
  'bs_aus:', [0xAB, 0x7A, 0xFA, 0x68, 0x28, 0x6B],
])
o = at(CODE); assert all(b == 0xFF for b in r[o:o+len(code)]); r[o:o+len(code)] = code
r[o0:o0+4] = bytes([0x22]+L(lab['bs']))
h = 0xFFC0
for _ in range(2):
    s = sum(r) & 0xFFFF; r[h+0x1E:h+0x20] = s.to_bytes(2,'little'); r[h+0x1C:h+0x1E] = (s^0xFFFF).to_bytes(2,'little')
open(pfad,'wb').write(d); print("Bossraum-Staerke eingebaut, %d Bytes" % len(code))
