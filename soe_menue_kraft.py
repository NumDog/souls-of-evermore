# Ring-Menue: rechts "alt -> neu" zeigt die ECHTE Waffenkraft inkl. "+N" (jedes Plus = +50 % der Grundkraft, wie im Kampf, F0:0280).
# 8E:A4A2 LDA $C40000,X = Kraft der ausgeruesteten Waffe ($0ABA), 8E:A4D1 = Kraft der ausgewaehlten Waffe (Ring-Eintrag auf dem Stapel).
import sys; sys.path.insert(0, __file__.rsplit('/',1)[0]); from asm import assemble
pfad = sys.argv[1]
d = bytearray(open(pfad,'rb').read()); H = len(d) % 1024; r = memoryview(d)[H:]
def at(x): return x & 0x3FFFFF if (x>>16) >= 0xC0 else (((x>>16)&0x3F)<<16)|(x&0xFFFF)
CODE = 0xF03B00
code,_ = assemble(CODE, [
  # --- aktuelle Waffe
  'ha:', [0xBF,0x00,0x00,0xC4, 0xDA,0x5A,0x48, 0xAF,0xBA,0x0A,0x7E, 0x29,0xFF,0x00], ('jsr','bonus'), [0x68,0x7A,0xFA,0x6B],
  # --- ausgewaehlte Waffe: Ring-Eintrag liegt beim Aufrufer auf 1,S -> hier 10,S
  'hb:', [0xBF,0x00,0x00,0xC4, 0xDA,0x5A,0x48, 0xA3,0x0A, 0xAA, 0xBF,0x06,0x00,0x8E, 0x29,0xFF,0x00], ('jsr','bonus'), [0x68,0x7A,0xFA,0x6B],
  # --- bonus: A = Waffen-ID, 3,S = Kraft -> 3,S = Kraft + n * Kraft/2 (n = Plus-Zaehler)
  'bonus:', [0xC9,0x02,0x00], ('bra8',0x90,'nichts'), [0xC9,0x1B,0x00], ('bra8',0xB0,'nichts'),
  [0x4A, 0x3A, 0x48, 0x4A, 0xAA, 0x68, 0x29,0x01,0x00, 0xA8],             # X = Byte, Y = oberes Nibble?
  [0xBF,0x50,0x22,0x7E, 0xC0,0x00,0x00], ('bra8',0xF0,'unten'), [0x4A,0x4A,0x4A,0x4A],
  'unten:', [0x29,0x0F,0x00], ('bra8',0xF0,'nichts'), [0xAA],
  [0xA3,0x03, 0x4A, 0x48],                                               # 1,S = Kraft/2 ; Kraft jetzt 5,S
  'schleife:', [0xA3,0x05, 0x18, 0x63,0x01, 0x83,0x05, 0xCA], ('bra8',0xD0,'schleife'),
  [0x68],
  'nichts:', [0x60],
])
o = at(CODE); assert all(b == 0xFF for b in r[o:o+len(code)]); r[o:o+len(code)] = code
HB = CODE + code.index(bytes([0xBF,0x00,0x00,0xC4]), 4)
for site, ziel in ((0x8EA4A2, CODE), (0x8EA4D1, HB)):
    o = at(site); assert bytes(r[o:o+4]) == bytes([0xBF,0x00,0x00,0xC4]), (hex(site), bytes(r[o:o+4]).hex())
    r[o:o+4] = bytes([0x22, ziel&0xFF, (ziel>>8)&0xFF, ziel>>16])
h = 0xFFC0
for _ in range(2):
    c = sum(r) & 0xFFFF; r[h+0x1E:h+0x20] = c.to_bytes(2,'little'); r[h+0x1C:h+0x1E] = (c^0xFFFF).to_bytes(2,'little')
open(pfad,'wb').write(d); print("Ring-Menue: echte Waffenkraft eingebaut, %d Bytes" % len(code))
