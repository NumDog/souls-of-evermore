# Formel +N (v88): Zaehler je Formel als Nibble in 7E:20B0 + i/2 (gerade i = unteres Nibble), max 15.
#  - Formel-Menue (CD:C4A4) und Ringmenue (ueber soe_menue_plus 'keine' -> F0:9080) zeigen "Name+N" (Ringmenue zusaetzlich " L<Stufe>", Wunsch Max).
#  - Schaden: in der Alchemie-Schadensrechnung (D1:CC05, Ergebnis von Stufen-Multiplikator x Grundwert / Ziele)
#    wird der Wert mit (1 + 0,25*N) multipliziert (gilt auch fuer Heil-Formeln, die denselben Weg nehmen).
#  - F0:9040 PLUS1 (X = 2i) wird vom Chaos-Fund (soe_zufall_live) benutzt.
import sys; sys.path.insert(0, __file__.rsplit('/',1)[0]); from asm import assemble
pfad = sys.argv[1]
d = bytearray(open(pfad,'rb').read()); H = len(d) % 1024; r = memoryview(d)[H:]
def at(x): return x & 0x3FFFFF if (x>>16) >= 0xC0 else (((x>>16)&0x3F)<<16)|(x&0xFFFF)
ZAHL, BAUE, PLUS1, RINGF, MENU, KRAFT = 0xF09000, 0xF09180, 0xF09040, 0xF09080, 0xF090C0, 0xF090E0
def L(a): return [a&0xFF,(a>>8)&0xFF,a>>16]
ZAEHL = 0x7E20B0; NAMTAB = 0xC5036F; PUF = 0xE800        # Puffer 7E:E800 + 32*i
teile = {}
# ZAHL: X = 2i -> A = N (16 bit, Z gesetzt wenn 0). Aufrufer M=16.
teile[ZAHL] = [[0x08, 0xC2,0x30, 0xDA, 0x8A, 0x4A,0x4A, 0xAA, 0xBF]+L(ZAEHL), ('bra8',0x90,'u'),
               [0x4A,0x4A,0x4A,0x4A], 'u:', [0xFA, 0x28, 0x29,0x0F,0x00, 0x6B]]
# BAUE: X = 2i, A = N, $22 = Name (Bank C5) -> Puffer "Name+N" (+N nur wenn N>0), bei 7E:E332 != 0 noch " L<Stufe>"
def ziffern(tag):   # A (8 bit, 0..19) als Zahl an Puffer,X
    return [0xC9,10], ('bra8',0x90,tag), [0x38,0xE9,10, 0x48, 0xA9,0x31, 0x9F,0x00,0x00,0x7E, 0xE8, 0x68], tag+':', [0x18,0x69,0x30, 0x9F,0x00,0x00,0x7E, 0xE8]
teile[BAUE] = [[0xDA,0x5A,0x48, 0xBF,0x98,0x2F,0x7E, 0x48,               # PHX PHY PHA(N) ; Stufe (wie im Formel-Menue, ab 0) -> PHA
                0x8A,0x0A,0x0A,0x0A,0x0A, 0x18,0x69,PUF&0xFF,PUF>>8, 0xAA, 0xDA,   # Puffer-Start -> PHX (1,S) ; L 3,S ; N 5,S
                0xA9,0xC5,0x00,0x85,0x24, 0xE2,0x20, 0xA0,0x00,0x00],
               'k:', [0xB7,0x22], ('bra8',0xF0,'ke'), [0x9F,0x00,0x00,0x7E, 0xE8,0xC8], ('bra8',0x80,'k'),
               'ke:', [0xA3,0x05], ('bra8',0xF0,'np'), [0xA9,0x2B, 0x9F,0x00,0x00,0x7E, 0xE8, 0xA3,0x05], *ziffern('z1'),
               'np:', [0xAF,0x32,0xE3,0x7E], ('bra8',0xF0,'fe'),
               [0xA9,0x20, 0x9F,0x00,0x00,0x7E, 0xE8, 0xA9,0x4C, 0x9F,0x00,0x00,0x7E, 0xE8, 0xA3,0x03], *ziffern('z2'),
               'fe:', [0xA9,0x00, 0x9F,0x00,0x00,0x7E, 0xC2,0x20,
                       0x68, 0x85,0x22, 0xA9,0x7E,0x00, 0x85,0x24, 0x68, 0x68, 0x7A, 0xFA, 0x6B]]
# PLUS1: X = 2i -> Nibble +1 (max 15), alles erhalten
teile[PLUS1] = [[0x08, 0xC2,0x30, 0xDA, 0x48, 0x8A, 0x4A,0x4A, 0xAA, 0xE2,0x20, 0xBF]+L(ZAEHL), ('bra8',0xB0,'h'),
                [0x29,0x0F, 0xC9,0x0F], ('bra8',0xF0,'v'), [0xBF]+L(ZAEHL)+[0x1A], ('bra8',0x80,'s'),
                'h:', [0x29,0xF0, 0xC9,0xF0], ('bra8',0xF0,'v'), [0xBF]+L(ZAEHL)+[0x18,0x69,0x10],
                's:', [0x9F]+L(ZAEHL), 'v:', [0xC2,0x30, 0x68, 0xFA, 0x28, 0x6B]]
# RINGF: aus soe_menue_plus (Stack: PHX PHY), $22 = Name. Formel suchen, ggf. "+N".
teile[RINGF] = [[0xA2,0x00,0x00], 's:', [0xBF]+L(NAMTAB)+[0xC5,0x22], ('bra8',0xF0,'t'),
                [0xE8,0xE8, 0xE0,70,0x00], ('bra8',0x90,'s'),
                'n:', [0xA9,0xC5,0x00,0x85,0x24, 0x7A,0xFA,0x6B],
                't:', [0xE2,0x20, 0xA9,0x01, 0x8F,0x32,0xE3,0x7E, 0xC2,0x20, 0x22]+L(ZAHL)+[0x22]+L(BAUE), [0xA9,0xC5,0x00, 0x7A,0xFA,0x6B]]
# MENU: ersetzt LDA $C5036F,X ; STA $22 in CD:C4A4 (X = 2i)
teile[MENU] = [[0xBF]+L(NAMTAB)+[0x85,0x22, 0x22]+L(ZAHL), ('bra8',0xF0,'r'),
               [0x48, 0xE2,0x20, 0xA9,0x00, 0x8F,0x32,0xE3,0x7E, 0xC2,0x20, 0x68, 0x22]+L(BAUE), 'r:', [0x6B]]
# KRAFT: ersetzt LDA $004214 ; STA $12 in D1:CC05 (X = 2i, Y = Effekt-Objekt). Ergebnis q + (q/4)*N, A = $12.
teile[KRAFT] = [[0xAF,0x14,0x42,0x00, 0x85,0x12, 0x22]+L(ZAHL), ('bra8',0xF0,'f'),
                [0x5A, 0xA8, 0xA5,0x12, 0xC9,0x00,0x10], ('bra8',0xB0,'gross'),
                # q < 4096: genau, q + (q*N)/4
                [0xA9,0x00,0x00], 'm:', [0x18, 0x65,0x12, 0x88], ('bra8',0xD0,'m'),
                [0x4A,0x4A, 0x18, 0x65,0x12], ('bra8',0x80,'st'),
                # q >= 4096: q + (q/4)*N (Rundung egal), Deckel 0xFFFF
                'gross:', [0xA5,0x12, 0x4A,0x4A, 0x85,0x02, 0xA5,0x12],
                'l:', [0x18, 0x65,0x02], ('bra8',0xB0,'c'), [0x88], ('bra8',0xD0,'l'), ('bra8',0x80,'st'),
                'c:', [0xA9,0xFF,0xFF], 'st:', [0x85,0x12, 0x7A], 'f:', [0xA5,0x12, 0x6B]]
grenzen = sorted(teile) + [0xF09280]
for i,a in enumerate(sorted(teile)):
    c,_ = assemble(a, teile[a]); assert a+len(c) <= grenzen[i+1], (hex(a),len(c))
    o = at(a); assert all(b == 0xFF for b in r[o:o+len(c)]), hex(a); r[o:o+len(c)] = c
for adr,alt,neu in ((0xCDC4A4, [0xBF,0x6F,0x03,0xC5,0x85,0x22], MENU), (0xD1CC05, [0xAF,0x14,0x42,0x00,0x85,0x12], KRAFT)):
    o = at(adr); assert bytes(r[o:o+6]) == bytes(alt), (hex(adr), bytes(r[o:o+6]).hex())
    r[o:o+6] = bytes([0x22]+L(neu)+[0xEA,0xEA])
# Ringmenue-Kopfzeile beim Formel-Ring (8E:A6F0, gleiches Muster wie 8E:A479) -> dieselbe Ring-Routine aus soe_menue_plus
o = at(0x8EA6F0); assert bytes(r[o:o+7]) == bytes([0x85,0x22,0xA9,0xC5,0x00,0x85,0x24]), bytes(r[o:o+7]).hex()
r[o:o+7] = bytes([0x22,0x00,0x0F,0xF0,0xEA,0xEA,0xEA])
h = 0xFFC0
for _ in range(2):
    c = sum(r) & 0xFFFF; r[h+0x1E:h+0x20] = c.to_bytes(2,'little'); r[h+0x1C:h+0x1E] = (c^0xFFFF).to_bytes(2,'little')
open(pfad,'wb').write(d); print("Formel +N Anzeige/Kraft eingebaut")
