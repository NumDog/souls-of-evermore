  'xph:', [0xBF,0x23,0x00,0x8E, 0x8F]+lng(V0), [0xBF,0x25,0x00,0x8E, 0x8F]+lng(V1), ('jsr','hoe_x'), ('jsr','skal'), [0x22,0x00,0x9C,0xF0],
  [0x18, 0xAF]+lng(V0), [0x6F,0x93,0x0A,0x7E, 0x8F,0x93,0x0A,0x7E, 0xAF]+lng(V1), [0x6F,0x95,0x0A,0x7E, 0x8F,0x95,0x0A,0x7E, 0x22,0x1F,0x80,0xF1, 0xAF,0x95,0x0A,0x7E, 0x6B],
