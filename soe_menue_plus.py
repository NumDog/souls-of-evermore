# Ringmenue: Waffen mit +N (Zaehler $7E2250..) bekommen " +N" hinter den Namen. Hook 8E:A479 (STA $22 ; LDA #$00C5 ; STA $24).
import sys; sys.path.insert(0, __file__.rsplit('/',1)[0]); from asm import assemble
pfad = sys.argv[1]
d = bytearray(open(pfad,'rb').read()); H = len(d) % 1024; r = memoryview(d)[H:]
def at(x): return x & 0x3FFFFF if (x>>16) >= 0xC0 else (((x>>16)&0x3F)<<16)|(x&0xFFFF)
NAMEN = [0x07A0,0x077C,0x0789,0x0793,0x07AF,0x07BB,0x07C5,0x07CF,0x07D7,0x07DD,0x07E9,0x07F8]   # Waffen-ID 02..18
for p in NAMEN: assert r[0x50000+p-1] == 0, hex(p)            # jeder Name beginnt nach einer Null
RING, TAB = 0xF00F00, 0xF00FC0
code,_ = assemble(RING, [
  [0x85,0x22, 0xDA,0x5A],                                   # STA $22 ; PHX PHY
  [0xA2,0x00,0x00],
  'such:', [0xDF,TAB&0xFF,(TAB>>8)&0xFF,TAB>>16], ('bra8',0xF0,'gefunden'),
  [0xE8,0xE8,0xE0,24,0x00], ('bra8',0x90,'such'),
  'keine:', [0x5C,0x80,0x90,0xF0],                         # v88: keine Waffe mit +N -> Formel-Pruefung (F0:9080, soe_formel_anzeige.py)
  'gefunden:', [0x8A, 0x18, 0x69,0x02,0x00, 0x22,0x00,0xB0,0xF1], ('bra8',0xF0,'keine'),   # v122: ID = X+2, JSL WGET (bis +99)
  [0x48, 0xA9,0xC5,0x00,0x85,0x24],                         # PHA (Plus) ; $24 = C5 fuer [$22]
  [0xE2,0x20, 0xA0,0x00,0x00, 0xA2,0x00,0x00],              # SEP #$20 ; Y=X=0
  'kopie:', [0xB7,0x22], ('bra8',0xF0,'ende'), [0x9F,0x40,0x7E,0x30, 0xC8,0xE8], ('bra8',0x80,'kopie'),
  'ende:', [0xA9,0x20,0x9F,0x40,0x7E,0x30,0xE8, 0xA9,0x2B,0x9F,0x40,0x7E,0x30,0xE8],   # " +"
  [0xA3,0x01, 0xA0,0x00,0x00], 'zehn:', [0xC9,10], ('bra8',0x90,'z_e'), [0x38, 0xE9,10, 0xC8], ('bra8',0x80,'zehn'),
  'z_e:', [0x48, 0x98], ('bra8',0xF0,'z_k'), [0x18, 0x69,0x30, 0x9F,0x40,0x7E,0x30,0xE8], 'z_k:', [0x68],
  'einer:', [0x18,0x69,0x30, 0x9F,0x40,0x7E,0x30,0xE8, 0xA9,0x00,0x9F,0x40,0x7E,0x30],
  [0xC2,0x20, 0xA9,0x40,0x7E,0x85,0x22, 0xA9,0x30,0x00,0x85,0x24],   # $22/$24 -> Puffer $30:7E40
  [0x68, 0xA9,0xC5,0x00, 0x7A,0xFA,0x6B],                   # PLA ; A wie Original ; PLY PLX RTL
])
tab = b''.join(p.to_bytes(2,'little') for p in NAMEN)
for adr,c in ((RING,code),(TAB,tab)):
    o=at(adr); assert all(b==0xFF for b in r[o:o+len(c)]), hex(adr); r[o:o+len(c)]=c
o=at(0x8EA479); assert bytes(r[o:o+7])==bytes([0x85,0x22,0xA9,0xC5,0x00,0x85,0x24]), bytes(r[o:o+7]).hex()
r[o:o+7]=bytes([0x22,RING&0xFF,(RING>>8)&0xFF,RING>>16,0xEA,0xEA,0xEA])
h=0xFFC0
for _ in range(2):
    c=sum(r)&0xFFFF; r[h+0x1E:h+0x20]=c.to_bytes(2,'little'); r[h+0x1C:h+0x1E]=(c^0xFFFF).to_bytes(2,'little')
open(pfad,'wb').write(d); print("Ringmenue +N eingebaut, %d Bytes"%len(code))
