# Blutfleck sichtbar machen: An der Todesstelle leuchtet der blaue Wiederbelebungs-Kreis (Effekt Typ 8, wie Elfenstaub).
# Effekte haengen immer an einem Besitzer-Objekt ($28/$2E) und lesen dessen Position (+1A/+1C). Statt eines echten
# Objekts (Fels war sichtbar und im Weg) nehmen wir ein Schein-Objekt in freiem WRAM 7E:FF00 (0x8E Bytes): Kopie der
# Jungen-Daten mit der Position der Todesstelle. Es steht in keiner Objektliste -> nicht gezeichnet, kein Hindernis.
# Aufruf jedes Bild aus soe_aufstehen.py ('fleck'), reset bei Kartenwechsel ('karte').
# SRAM: 7FF5 Zustand (0 aus, 2 aktiv), 7FFA Besitzer (FF00, fuer Ton-Stummschaltung in soe_ton_fremd), 7FFC Zaehler.
import sys; sys.path.insert(0, __file__.rsplit('/',1)[0]); from asm import assemble
pfad = sys.argv[1]
d = bytearray(open(pfad,'rb').read()); H = len(d) % 1024; r = memoryview(d)[H:]
def at(x): return x & 0x3FFFFF if (x>>16) >= 0xC0 else (((x>>16)&0x3F)<<16)|(x&0xFFFF)
CODE = 0xF04800
SCHEIN = 0xFF00
code, lab = assemble(CODE, [
  'reset:', [0x08, 0xE2,0x20, 0xA9,0x00, 0x8F,0xF5,0x7F,0x30, 0x28, 0x6B],
  'glanz:', [0x08, 0xC2,0x30, 0x8B, 0xDA, 0x5A],
  # nur wenn Blutfleck gueltig, im Todesraum, keine Rueckkehr laeuft
  [0xAF,0xED,0x7E,0x30, 0x29,0xFF,0x00], ('bra8',0xF0,'aus'),
  [0xAF,0xF6,0x7E,0x30], ('bra8',0xD0,'aus'),
  [0xAF,0xEC,0x7E,0x30, 0x4F,0xDB,0x0A,0x7E, 0x29,0xFF,0x00], ('bra8',0xD0,'aus'),
  [0xAF,0xF5,0x7F,0x30, 0x29,0xFF,0x00, 0xC9,0x02,0x00], ('bra8',0xF0,'aktiv'),
  # einschalten
  [0xA9,SCHEIN&0xFF,SCHEIN>>8, 0x8F,0xFA,0x7F,0x30, 0xA9,0x01,0x00, 0x8F,0xFC,0x7F,0x30],
  [0xE2,0x20, 0xA9,0x02, 0x8F,0xF5,0x7F,0x30, 0xC2,0x20],
  'aktiv:', [0xAF,0xFC,0x7F,0x30, 0x3A, 0x8F,0xFC,0x7F,0x30], ('bra8',0xF0,'e_los'),
  'aus:', [0x7A, 0xFA, 0xAB, 0x28, 0x6B],                                        # PLY PLX PLB PLP
  'e_los:',
  [0xA9,0x40,0x00, 0x8F,0xFC,0x7F,0x30],
  # Schein-Objekt = Kopie des Jungen (7E:4E89) mit Position der Todesstelle
  [0xA2,0x89,0x4E, 0xA0,SCHEIN&0xFF,SCHEIN>>8, 0xA9,0x8D,0x00, 0x54,0x7E,0x7E],   # MVN 7E,7E
  [0xAF,0xEA,0x7F,0x30, 0x8F,0x1A,SCHEIN>>8,0x7E, 0xAF,0xEC,0x7F,0x30, 0x8F,0x1C,SCHEIN>>8,0x7E],
  [0xF4,0x7E,0x7E, 0xAB, 0xAB],                                                  # DBR = 7E
  [0x22,0x59,0x97,0x91], [0x98], ('bra8',0xF0,'aus'),                            # freier Effekt-Platz (Y)
  [0xA9,SCHEIN&0xFF,SCHEIN>>8, 0x99,0x28,0x00, 0x99,0x2E,0x00, 0xA9,0x00,0x00, 0x99,0x30,0x00],
  [0xA9,0x3C,0x00, 0x99,0x2A,0x00, 0xA2,0x08,0x00, 0x22,0x3E,0x97,0x91],
  ('bra8',0x80,'aus'),
  # Effekt-Befehl „Blitz-Palette“ (91:C4DD, JML von 91:C4ED): Halter < 4E89 (Gegner) -> freie Palette (90:CEB5),
  # Junge -> Palette 6, sonst Palette 7 (= Hund-Palette -> Hund/Gegner blau). Schein-Objekt FF00 -> Gegner-Weg (91:C50D).
  'blitz:', [0xBE,0x2E,0x00, 0xE0,SCHEIN&0xFF,SCHEIN>>8], ('bra8',0xF0,'b_frei'),
  [0xE0,0x89,0x4E, 0x5C,0xF3,0xC4,0x91],                                         # Original CPX #$4E89, weiter bei BCC
  'b_frei:', [0x5C,0x0D,0xC5,0x91],
])
assert lab['reset'] == 0xF04800 and lab['glanz'] == 0xF0480B, lab
assert (SCHEIN & 0xFF) == 0x00   # +1A/+1C Adressen oben setzen Low-Byte 00 voraus
o = at(0x91C4ED); assert bytes(r[o:o+11]) == bytes([0xBE,0x2E,0x00,0xE0,0x89,0x4E,0x90,0x18,0x48,0xA9,0x0C]), bytes(r[o:o+11]).hex()
r[o:o+6] = bytes([0x5C, lab['blitz']&0xFF, (lab['blitz']>>8)&0xFF, 0xF0, 0xEA, 0xEA])
o = at(CODE); assert all(b == 0xFF for b in r[o:o+len(code)]) and CODE + len(code) <= 0xF04A00; r[o:o+len(code)] = code
h = 0xFFC0
for _ in range(2):
    c = sum(r) & 0xFFFF; r[h+0x1E:h+0x20] = c.to_bytes(2,'little'); r[h+0x1C:h+0x1E] = (c^0xFFFF).to_bytes(2,'little')
open(pfad,'wb').write(d); print("Blutfleck-Kreis eingebaut, %d Bytes, glanz=%X reset=%X" % (len(code), lab['glanz'], lab['reset']))
